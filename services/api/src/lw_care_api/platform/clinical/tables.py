"""Additive EMR storage. Protected content is encrypted; signed history is append-only."""

from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    CheckConstraint,
    Column,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Table,
    Text,
    UniqueConstraint,
)

from ..db import SCHEMA, identifier, metadata

sites = Table(
    "clinical_sites",
    metadata,
    identifier(),
    Column("facility_id", ForeignKey(f"{SCHEMA}.facilities.id"), unique=True, nullable=False),
    Column("authority_node_id", String(80), nullable=False),
    Column("authority_epoch", String(40), nullable=False),
    Column("services", JSON, nullable=False),
    Column("policy_reference", Text, nullable=False),
    Column("manual_medicine_policy", Text, nullable=False),
    Column("valid_from", String(40), nullable=False),
    Column("valid_until", String(40), nullable=False),
    Column("active", Boolean, nullable=False),
    Column("version", Integer, nullable=False),
    Column("approved_by", String(36), nullable=False),
)
privileges = Table(
    "clinical_privileges",
    metadata,
    identifier(),
    Column("facility_id", ForeignKey(f"{SCHEMA}.facilities.id"), nullable=False),
    Column("account_id", ForeignKey(f"{SCHEMA}.accounts.id"), nullable=False),
    Column("services", JSON, nullable=False),
    Column("capabilities", JSON, nullable=False),
    Column("professional_reference", Text, nullable=False),
    Column("valid_from", String(40), nullable=False),
    Column("valid_until", String(40), nullable=False),
    Column("revoked", Boolean, nullable=False, default=False),
    Column("approved_by", String(36), nullable=False),
)
records = Table(
    "clinical_records",
    metadata,
    identifier(),
    Column("facility_id", ForeignKey(f"{SCHEMA}.facilities.id"), nullable=False),
    Column("patient_id", String(36)),
    Column("encounter_id", String(36)),
    Column("kind", String(32), nullable=False),
    Column("status", String(32), nullable=False),
    Column("service", String(80), nullable=False),
    Column("confidentiality", String(20), nullable=False, default="STANDARD"),
    Column("authority_node_id", String(80), nullable=False),
    Column("authority_epoch", String(40), nullable=False),
    Column("version", Integer, nullable=False),
    Column("content_ciphertext", Text, nullable=False),
    Column("identifier_hash", String(64)),
    Column("search_tokens", JSON),
    Column("created_by", String(36), nullable=False),
    Column("created_at", String(40), nullable=False),
    Column("updated_at", String(40), nullable=False),
    UniqueConstraint("facility_id", "kind", "identifier_hash"),
)
Index("ix_clinical_scope", records.c.facility_id, records.c.kind, records.c.patient_id)
Index("ix_clinical_encounter", records.c.facility_id, records.c.encounter_id)
memberships = Table(
    "clinical_memberships",
    metadata,
    identifier(),
    Column("facility_id", String(36), nullable=False),
    Column("patient_id", String(36), nullable=False),
    Column("encounter_id", ForeignKey(f"{SCHEMA}.clinical_records.id"), nullable=False),
    Column("account_id", ForeignKey(f"{SCHEMA}.accounts.id"), nullable=False),
    Column("valid_until", String(40), nullable=False),
    Column("active", Boolean, nullable=False),
    UniqueConstraint("encounter_id", "account_id"),
)
events = Table(
    "clinical_events",
    metadata,
    identifier(),
    Column("facility_id", String(36), nullable=False),
    Column("patient_id", String(36)),
    Column("record_id", ForeignKey(f"{SCHEMA}.clinical_records.id"), nullable=False),
    Column("version", Integer, nullable=False),
    Column("event_contract_id", String(40), nullable=False),
    Column("action", String(80), nullable=False),
    Column("actor_id", String(36), nullable=False),
    Column("occurred_at", String(40), nullable=False),
    Column("recorded_at", String(40), nullable=False),
    Column("authority_node_id", String(80), nullable=False),
    Column("authority_epoch", String(40), nullable=False),
    Column("previous_hash", String(64), nullable=False),
    Column("payload_hash", String(64), nullable=False),
    Column("signature", Text, nullable=False),
    Column("payload_ciphertext", Text, nullable=False),
    UniqueConstraint("record_id", "version"),
)
audit = Table(
    "clinical_audit",
    metadata,
    identifier(),
    Column("facility_id", String(36)),
    Column("actor_id", String(36)),
    Column("patient_id", String(36)),
    Column("action", String(80), nullable=False),
    Column("purpose", String(40), nullable=False),
    Column("outcome", String(20), nullable=False),
    Column("correlation_id", String(36), nullable=False),
    Column("recorded_at", String(40), nullable=False),
)
operations = Table(
    "clinical_operations",
    metadata,
    identifier(),
    Column("actor_id", String(36), nullable=False),
    Column("facility_id", String(36), nullable=False),
    Column("operation", String(240), nullable=False),
    Column("key", String(160), nullable=False),
    Column("request_hash", String(64), nullable=False),
    Column("response_ciphertext", Text, nullable=False),
    UniqueConstraint("actor_id", "operation", "key"),
)
beds = Table(
    "clinical_beds",
    metadata,
    identifier(),
    Column("facility_id", ForeignKey(f"{SCHEMA}.facilities.id"), nullable=False),
    Column("ward", String(120), nullable=False),
    Column("label", String(80), nullable=False),
    Column("active", Boolean, nullable=False),
    Column("stay_id", ForeignKey(f"{SCHEMA}.clinical_records.id"), unique=True),
    Column("version", Integer, nullable=False),
    UniqueConstraint("facility_id", "ward", "label"),
)
lots = Table(
    "clinical_stock_lots",
    metadata,
    identifier(),
    Column("facility_id", String(36), nullable=False),
    Column("product_id", ForeignKey(f"{SCHEMA}.clinical_records.id"), nullable=False),
    Column("batch", String(120), nullable=False),
    Column("expires_at", String(40), nullable=False),
    Column("quantity", Numeric(20, 6), nullable=False),
    Column("unit", String(40), nullable=False),
    Column("status", String(20), nullable=False),
    Column("version", Integer, nullable=False),
    UniqueConstraint("facility_id", "product_id", "batch"),
    CheckConstraint("quantity >= 0", name="clinical_stock_nonnegative"),
)
movements = Table(
    "clinical_stock_movements",
    metadata,
    identifier(),
    Column("lot_id", ForeignKey(f"{SCHEMA}.clinical_stock_lots.id"), nullable=False),
    Column("source_id", String(36), unique=True, nullable=False),
    Column("quantity", Numeric(20, 6), nullable=False),
    Column("reason", Text, nullable=False),
    Column("actor_id", String(36), nullable=False),
    Column("recorded_at", String(40), nullable=False),
)

ledger = Table(
    "clinical_ledger",
    metadata,
    identifier(),
    Column("facility_id", String(36), nullable=False),
    Column("source_id", ForeignKey(f"{SCHEMA}.clinical_records.id"), nullable=False),
    Column("leg", Integer, nullable=False),
    Column("account", String(40), nullable=False),
    Column("amount_minor", BigInteger, nullable=False),
    Column("currency", String(3), nullable=False),
    Column("recorded_at", String(40), nullable=False),
    UniqueConstraint("source_id", "leg"),
)

IMMUTABLE = (events, audit, movements, ledger)
